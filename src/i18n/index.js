// 支持 {var} 占位符，向后兼容（无 vars 时等同原 t(key)）
export function t(key, vars) {
  let s = messages[locale.value]?.[key] ?? key
  if (vars && typeof s === 'string') {
    s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m))
  }
  return s
}

export function setLocale(loc) {
  if (messages[loc]) locale.value = loc
}

// 手机/浏览器系统语言 → H5 三语之一（匹配不到返回 ''）
function fromSystemLanguage() {
  try {
    const raw = String((navigator && (navigator.language || navigator.userLanguage)) || '').toLowerCase()
    if (raw.startsWith('zh')) return 'zh'
    if (raw.startsWith('pt')) return 'pt'
    if (raw.startsWith('en')) return 'en'
  } catch (e) {
    /* 忽略 */
  }
  return ''
}

// 初始化界面语言。
//
// 产品规则（2026-08-31 定，坤哥拍板）：
//   **语言同时决定「界面语言」和「内容地区」：**
//   中文 → 界面中文 + 中国内容(CN)
//   葡萄牙语 → 界面葡语 + 巴西内容(BR)
//   英文 → 界面英文 + 全球内容(US)
//   地区不再独立切换，见 regionFromLocale()。
//
// 优先级：URL ?lang=（实测/联调）> bridge.getLocale()（Flutter 注入的手机/App 语言）
//        > navigator.language（系统语言兜底，原生未实现 getLocale 时生效）> zh
export async function initLocale() {
  try {
    const q = (new URLSearchParams(location.search).get('lang') || '').trim()
    if (q && messages[q]) {
      locale.value = q
      return
    }
  } catch (e) {
    /* location 不可用（如 SSR/沙箱）时忽略，走下面的桥 */
  }
  try {
    const loc = await bridge.getLocale()
    if (loc && messages[loc]) {
      locale.value = loc
      return
    }
  } catch (e) {
    /* 原生未实现 getLocale：继续用系统语言兜底 */
  }
  const sys = fromSystemLanguage()
  locale.value = sys && messages[sys] ? sys : 'zh'
}

export default { t, locale, setLocale, initLocale, regionFromLocale }
